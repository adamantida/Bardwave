/// Accept connections on `listener`, terminate TLS and hand the requests to
/// `app` until `shutdown` completes. The counterpart of `axum::serve` for
/// HTTPS: it keeps `TCP_NODELAY` (the audio frames are tiny) and the peer
/// address (`ConnectInfo`) the game-master panel needs to tell local clients
/// from remote ones.
pub async fn serve(
    listener: TcpListener,
    app: Router,
    acceptor: TlsAcceptor,
    shutdown: impl Future<Output = ()>,
) {
    tokio::pin!(shutdown);
    let mut connections: JoinSet<()> = JoinSet::new();
    loop {
        tokio::select! {
            _ = &mut shutdown => break,
            accepted = listener.accept() => match accepted {
                Ok((tcp, peer)) => {
                    let _ = tcp.set_nodelay(true);
                    connections.spawn(serve_connection(tcp, peer, acceptor.clone(), app.clone()));
                }
                Err(e) => {
                    // EMFILE and friends: back off instead of spinning.
                    warn!("TLS accept failed: {e}");
                    tokio::time::sleep(Duration::from_millis(50)).await;
                }
            },
            Some(_) = connections.join_next(), if !connections.is_empty() => {}
        }
    }
    drop(listener);
    // Listener sessions close themselves on the shared shutdown signal; give
    // them a moment, then cut whatever is left.
    let _ = tokio::time::timeout(Duration::from_secs(1), async {
        while connections.join_next().await.is_some() {}
    })
    .await;
    connections.abort_all();
}

async fn serve_connection(
    tcp: tokio::net::TcpStream,
    peer: SocketAddr,
    acceptor: TlsAcceptor,
    app: Router,
) {
    // Browsers drop the first connection to a self-signed server (they ask
    // the user); that is routine, so it is not a warning.
    let tls = match tokio::time::timeout(HANDSHAKE_TIMEOUT, acceptor.accept(tcp)).await {
        Ok(Ok(tls)) => tls,
        Ok(Err(e)) => {
            debug!("TLS handshake with {peer} failed: {e}");
            return;
        }
        Err(_) => {
            debug!("TLS handshake with {peer} timed out");
            return;
        }
    };
    let service =
        hyper::service::service_fn(move |request: hyper::Request<hyper::body::Incoming>| {
            let mut app = app.clone();
            async move {
                let mut request = request.map(axum::body::Body::new);
                request.extensions_mut().insert(ConnectInfo(peer));
                app.call(request).await
            }
        });
    let result = hyper::server::conn::http1::Builder::new()
        .timer(TokioTimer::new())
        .header_read_timeout(HEADER_TIMEOUT)
        .serve_connection(TokioIo::new(tls), service)
        .with_upgrades()
        .await;
    if let Err(e) = result {
        debug!("HTTPS connection from {peer} ended: {e}");
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn sans() -> SanSet {
        let mut s = SanSet::default();
        s.add_dns("localhost");
        s.add_dns("My Host"); // invalid: skipped
        s.add_dns("gm-pc");
        s.add_ip("127.0.0.1".parse().unwrap());
        s.add_ip("192.168.1.20".parse().unwrap());
        s
    }

    fn settings(dir: &Path) -> TlsSettings {
        TlsSettings {
            enabled: true,
            dir: Some(dir.join("tls")),
            ..Default::default()
        }
    }

    #[test]
    fn civil_dates_are_right() {
        assert_eq!(civil_from_days(0), (1970, 1, 1));
        assert_eq!(civil_from_days(19_783), (2024, 3, 1));
        assert_eq!(civil_from_days(-1), (1969, 12, 31));
    }

    #[test]
    fn fingerprint_is_hex_with_colons() {
        let fp = fingerprint_sha256(b"abc");
        assert_eq!(
            fp,
            "BA:78:16:BF:8F:01:CF:EA:41:41:40:DE:5D:AE:22:23:B0:03:61:A3:96:17:7A:9C:B4:10:FF:61:F2:00:15:AD"
        );
    }

    #[test]
    fn san_set_keeps_valid_names_only() {
        let s = sans();
        assert_eq!(s.dns, vec!["localhost", "gm-pc"]);
        assert_eq!(s.ips.len(), 2);
        assert!(s.names().contains(&"192.168.1.20".to_string()));
    }

    #[test]
    fn half_configured_paths_are_an_error() {
        let dir = tempfile_dir("half");
        let mut st = settings(&dir);
        st.cert = Some(dir.join("only-cert.pem"));
        assert!(matches!(
            load_or_create(&st, &sans()),
            Err(TlsError::HalfConfigured)
        ));
    }

    #[test]
    fn unreadable_custom_certificate_says_which_file() {
        let dir = tempfile_dir("unreadable");
        let mut st = settings(&dir);
        st.cert = Some(dir.join("nope.pem"));
        st.key = Some(dir.join("nope.key"));
        let err = load_or_create(&st, &sans()).err().expect("must fail");
        assert!(err.to_string().contains("nope.pem"), "{err}");
    }

    #[test]
    fn empty_pem_is_reported_as_no_certificate() {
        let dir = tempfile_dir("emptypem");
        let cert = dir.join("empty.pem");
        std::fs::write(&cert, "not a pem").unwrap();
        let err = load_custom(&cert, &cert).err().expect("must fail");
        assert!(matches!(err, TlsError::NoCertificate(_)), "{err}");
    }

    #[test]
    fn a_generated_certificate_is_reused_and_replaced_on_demand() {
        let dir = tempfile_dir("reuse");
        let st = settings(&dir);
        let first = load_or_create(&st, &sans()).unwrap();
        let second = load_or_create(&st, &sans()).unwrap();
        assert_eq!(
            first.info.fingerprint_sha256,
            second.info.fingerprint_sha256
        );
        assert_eq!(first.info.source, CertSource::SelfSigned);
        let third = regenerate_self_signed(&st.cert_dir(), &sans()).unwrap();
        assert_ne!(first.info.fingerprint_sha256, third.fingerprint_sha256);
        assert_eq!(
            stored_info(&st.cert_dir()).unwrap().fingerprint_sha256,
            third.fingerprint_sha256
        );
    }

    #[test]
    fn a_new_network_replaces_the_certificate() {
        let dir = tempfile_dir("network");
        let st = settings(&dir);
        let first = load_or_create(&st, &sans()).unwrap();

        // Same machine, one more address: still covered, kept.
        let mut more = sans();
        more.add_ip("10.1.1.1".parse().unwrap());
        let same = load_or_create(&st, &more).unwrap();
        assert_eq!(first.info.fingerprint_sha256, same.info.fingerprint_sha256);

        // Only addresses the certificate does not know: replaced.
        let mut moved = SanSet::default();
        moved.add_dns("localhost");
        moved.add_ip("127.0.0.1".parse().unwrap());
        moved.add_ip("172.16.0.9".parse().unwrap());
        let fresh = load_or_create(&st, &moved).unwrap();
        assert_ne!(first.info.fingerprint_sha256, fresh.info.fingerprint_sha256);
        assert!(fresh.info.names.contains(&"172.16.0.9".to_string()));
    }

    #[test]
    fn an_expiring_certificate_is_replaced() {
        let dir = tempfile_dir("expiry");
        let st = settings(&dir);
        let first = load_or_create(&st, &sans()).unwrap();
        let later = now_unix() + (VALIDITY_DAYS - 5) * 86_400;
        assert!(load_generated(&st.cert_dir(), &sans(), later).is_err());
        assert!(load_generated(&st.cert_dir(), &sans(), now_unix()).is_ok());
        drop(first);
    }

    #[cfg(unix)]
    #[test]
    fn the_key_is_private() {
        use std::os::unix::fs::PermissionsExt;
        let dir = tempfile_dir("perm");
        let st = settings(&dir);
        load_or_create(&st, &sans()).unwrap();
        let mode = |p: PathBuf| std::fs::metadata(p).unwrap().permissions().mode() & 0o777;
        assert_eq!(mode(st.cert_dir().join(KEY_FILE)), 0o600);
        assert_eq!(mode(st.cert_dir()), 0o700);
        assert!(!st.cert_dir().join("key.tmp").exists());
    }

    #[test]
    fn a_custom_certificate_is_used_as_it_is() {
        let dir = tempfile_dir("custom");
        let generated = load_or_create(&settings(&dir), &sans()).unwrap();
        let st = TlsSettings {
            enabled: true,
            cert: Some(dir.join("tls").join(CERT_FILE)),
            key: Some(dir.join("tls").join(KEY_FILE)),
            dir: Some(dir.join("elsewhere")),
        };
        let custom = load_or_create(&st, &sans()).unwrap();
        assert_eq!(custom.info.source, CertSource::Custom);
        assert_eq!(
            custom.info.fingerprint_sha256,
            generated.info.fingerprint_sha256
        );
        assert!(!dir.join("elsewhere").exists());
        assert!(acceptor(&custom).is_ok());
    }

    #[test]
    fn a_key_of_another_certificate_is_refused() {
        let dir = tempfile_dir("mismatch");
        let a = dir.join("a");
        let b = dir.join("b");
        let ia = generate(&a, &sans(), now_unix()).unwrap();
        generate(&b, &sans(), now_unix()).unwrap();
        let err = load_custom(&a.join(CERT_FILE), &b.join(KEY_FILE))
            .err()
            .expect("must fail");
        assert!(matches!(err, TlsError::KeyMismatch(_)), "{err}");
        drop(ia);
    }

    #[test]
    fn config_paths_trim_and_ignore_empty_strings() {
        let server = crate::config::ServerConfig {
            tls: true,
            tls_cert: Some("  ".into()),
            tls_key: Some("/k.pem".into()),
            ..Default::default()
        };
        let st = TlsSettings::from_config(&server);
        assert!(st.enabled);
        assert_eq!(st.cert, None);
        assert_eq!(st.key, Some(PathBuf::from("/k.pem")));
    }

    /// A unique empty directory under the system temp dir, removed on drop
    /// (tests never touch the real data directory).
    struct TempDir(PathBuf);

    impl std::ops::Deref for TempDir {
        type Target = Path;
        fn deref(&self) -> &Path {
            &self.0
        }
    }

    impl Drop for TempDir {
        fn drop(&mut self) {
            let _ = std::fs::remove_dir_all(&self.0);
        }
    }

    fn tempfile_dir(tag: &str) -> TempDir {
        let dir = std::env::temp_dir().join(format!(
            "bardwave-tls-{tag}-{}-{}",
            std::process::id(),
            uuid::Uuid::new_v4().simple()
        ));
        std::fs::create_dir_all(&dir).unwrap();
        TempDir(dir)
    }
}
