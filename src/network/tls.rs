/// Metadata kept next to a generated certificate.
#[derive(Debug, Serialize, Deserialize)]
struct Meta {
    /// DNS names and addresses the certificate covers.
    names: Vec<String>,
    not_before: i64,
    not_after: i64,
}

fn now_unix() -> i64 {
    std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.as_secs() as i64)
        .unwrap_or(0)
}

/// Days since 1970-01-01 to (year, month, day), proleptic Gregorian.
fn civil_from_days(days: i64) -> (i32, u8, u8) {
    let z = days + 719_468;
    let era = z.div_euclid(146_097);
    let doe = z.rem_euclid(146_097);
    let yoe = (doe - doe / 1460 + doe / 36_524 - doe / 146_096) / 365;
    let y = yoe + era * 400;
    let doy = doe - (365 * yoe + yoe / 4 - yoe / 100);
    let mp = (5 * doy + 2) / 153;
    let d = doy - (153 * mp + 2) / 5 + 1;
    let m = if mp < 10 { mp + 3 } else { mp - 9 };
    let y = if m <= 2 { y + 1 } else { y };
    (y as i32, m as u8, d as u8)
}

fn date_at(unix_secs: i64) -> (i32, u8, u8) {
    civil_from_days(unix_secs.div_euclid(86_400))
}

/// The UTC calendar date (year, month, day) of a Unix time, for showing an
/// expiry date in the GUI.
pub fn date_utc(unix_secs: i64) -> (i32, u8, u8) {
    date_at(unix_secs)
}

/// Load the operator's certificate and key.
fn load_custom(cert: &Path, key: &Path) -> Result<TlsMaterial, TlsError> {
    let certs = CertificateDer::pem_file_iter(cert)
        .map_err(|e| TlsError::CertRead {
            path: cert.to_path_buf(),
            reason: e.to_string(),
        })?
        .collect::<Result<Vec<_>, _>>()
        .map_err(|e| TlsError::CertRead {
            path: cert.to_path_buf(),
            reason: e.to_string(),
        })?;
    if certs.is_empty() {
        return Err(TlsError::NoCertificate(cert.to_path_buf()));
    }
    let key_der = PrivateKeyDer::from_pem_file(key).map_err(|e| TlsError::KeyRead {
        path: key.to_path_buf(),
        reason: e.to_string(),
    })?;
    let info = TlsInfo {
        fingerprint_sha256: fingerprint_sha256(&certs[0]),
        source: CertSource::Custom,
        cert_path: cert.to_path_buf(),
        names: Vec::new(),
        not_after: None,
    };
    check_pair(&certs, &key_der)?;
    Ok(TlsMaterial {
        certs,
        key: key_der,
        info,
    })
}

/// The key has to be one rustls can sign with and has to match the leaf.
fn check_pair(
    certs: &[CertificateDer<'static>],
    key: &PrivateKeyDer<'static>,
) -> Result<(), TlsError> {
    let signing = rustls::crypto::ring::sign::any_supported_type(key)
        .map_err(|e| TlsError::KeyMismatch(e.to_string()))?;
    let certified = rustls::sign::CertifiedKey::new(certs.to_vec(), signing);
    certified
        .keys_match()
        .map_err(|e| TlsError::KeyMismatch(e.to_string()))
}

/// Read a previously generated certificate when it is still good for `wanted`.
fn load_generated(dir: &Path, wanted: &SanSet, now: i64) -> Result<TlsMaterial, String> {
    let cert = dir.join(CERT_FILE);
    let key = dir.join(KEY_FILE);
    let meta: Meta = serde_json::from_slice(
        &std::fs::read(dir.join(META_FILE)).map_err(|e| format!("no metadata: {e}"))?,
    )
    .map_err(|e| format!("unreadable metadata: {e}"))?;

    if meta.not_after - now < RENEW_BEFORE_DAYS * 86_400 {
        return Err("it is about to expire".into());
    }
    if meta.not_before > now + 86_400 {
        return Err("its start date is in the future".into());
    }
    let external: Vec<&IpAddr> = wanted.external_ips().collect();
    if !external.is_empty()
        && !external
            .iter()
            .any(|ip| meta.names.iter().any(|n| *n == ip.to_string()))
    {
        return Err("none of this machine's current addresses is covered".into());
    }

    let mut material = load_custom(&cert, &key).map_err(|e| e.to_string())?;
    material.info.source = CertSource::SelfSigned;
    material.info.names = meta.names;
    material.info.not_after = Some(meta.not_after);
    Ok(material)
}

/// Create the key and the certificate and write them into `dir`.
fn generate(dir: &Path, sans: &SanSet, now: i64) -> Result<TlsMaterial, TlsError> {
    let generate_err = |e: rcgen::Error| TlsError::Generate(e.to_string());

    let mut params = rcgen::CertificateParams::new(sans.names()).map_err(generate_err)?;
    let mut name = rcgen::DistinguishedName::new();
    name.push(rcgen::DnType::CommonName, "Bardwave");
    name.push(rcgen::DnType::OrganizationName, "Bardwave (self-signed)");
    params.distinguished_name = name;
    params.key_usages = vec![rcgen::KeyUsagePurpose::DigitalSignature];
    params.extended_key_usages = vec![rcgen::ExtendedKeyUsagePurpose::ServerAuth];
    // A day of slack for clients whose clock is a little behind.
    let not_before = now - 86_400;
    let not_after = now + VALIDITY_DAYS * 86_400;
    let from = date_at(not_before);
    let to = date_at(not_after);
    params.not_before = rcgen::date_time_ymd(from.0, from.1, from.2);
    params.not_after = rcgen::date_time_ymd(to.0, to.1, to.2);

    let key_pair = rcgen::KeyPair::generate().map_err(generate_err)?;
    let certificate = params.self_signed(&key_pair).map_err(generate_err)?;

    let store = |reason: std::io::Error| TlsError::Store {
        path: dir.to_path_buf(),
        reason: reason.to_string(),
    };
    create_private_dir(dir).map_err(store)?;
    // The key goes first and the metadata last: the metadata is what marks the
    // set as complete, so an interrupted write is regenerated next time.
    write_private(&dir.join(KEY_FILE), key_pair.serialize_pem().as_bytes()).map_err(store)?;
    write_private(&dir.join(CERT_FILE), certificate.pem().as_bytes()).map_err(store)?;
    let meta = Meta {
        names: sans.names(),
        not_before,
        not_after,
    };
    let meta_json = serde_json::to_vec_pretty(&meta).map_err(|e| TlsError::Store {
        path: dir.to_path_buf(),
        reason: e.to_string(),
    })?;
    write_private(&dir.join(META_FILE), &meta_json).map_err(store)?;

    let der = certificate.der().clone();
    let key_der = PrivateKeyDer::try_from(key_pair.serialize_der())
        .map_err(|e| TlsError::Generate(e.to_string()))?;
    let certs = vec![der];
    check_pair(&certs, &key_der)?;
    Ok(TlsMaterial {
        info: TlsInfo {
            fingerprint_sha256: fingerprint_sha256(&certs[0]),
            source: CertSource::SelfSigned,
            cert_path: dir.join(CERT_FILE),
            names: meta.names,
            not_after: Some(not_after),
        },
        certs,
        key: key_der,
    })
}

/// `dir` (and parents); on Unix the leaf is `0700`.
fn create_private_dir(dir: &Path) -> std::io::Result<()> {
    std::fs::create_dir_all(dir)?;
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        std::fs::set_permissions(dir, std::fs::Permissions::from_mode(0o700))?;
    }
    Ok(())
}

/// Write `bytes` to `path` atomically; the file is `0600` from the first byte
/// on Unix, so the key is never readable by other users, even briefly.
fn write_private(path: &Path, bytes: &[u8]) -> std::io::Result<()> {
    use std::io::Write;
    let tmp = path.with_extension("tmp");
    let _ = std::fs::remove_file(&tmp);
    let mut options = std::fs::OpenOptions::new();
    options.write(true).create_new(true);
    #[cfg(unix)]
    {
        use std::os::unix::fs::OpenOptionsExt;
        options.mode(0o600);
    }
    let mut file = options.open(&tmp)?;
    file.write_all(bytes)?;
    file.sync_all()?;
    drop(file);
    std::fs::rename(&tmp, path)
}

/// Make the certificate the server will use.
///
/// * both `cert` and `key` set: those files;
/// * neither: the generated one in `settings.cert_dir()`, reused when it is
///   still good for `sans`, created otherwise;
/// * only one of them: an error (it is a half-finished edit, and silently
///   falling back would hide it).
pub fn load_or_create(settings: &TlsSettings, sans: &SanSet) -> Result<TlsMaterial, TlsError> {
    match (&settings.cert, &settings.key) {
        (Some(cert), Some(key)) => load_custom(cert, key),
        (None, None) => {
            let dir = settings.cert_dir();
            let now = now_unix();
            match load_generated(&dir, sans, now) {
                Ok(material) => Ok(material),
                Err(why) => {
                    if dir.join(CERT_FILE).exists() {
                        info!("Replacing the self-signed certificate: {why}");
                    }
                    generate(&dir, sans, now)
                }
            }
        }
        _ => Err(TlsError::HalfConfigured),
    }
}

/// Throw the generated certificate away and make a new one (the "new
/// certificate" button). Phones that trusted the old one will warn again.
pub fn regenerate_self_signed(dir: &Path, sans: &SanSet) -> Result<TlsInfo, TlsError> {
    generate(dir, sans, now_unix()).map(|m| m.info)
}

/// Read and check the operator's own certificate and key without serving
/// anything (the HTTPS settings in the GUI call this on a worker thread to tell
/// the operator what is wrong before the next Start). Reads the same files, in
/// the same order and with the same errors, as [`load_or_create`].
pub fn check_custom(cert: &Path, key: &Path) -> Result<TlsInfo, TlsError> {
    load_custom(cert, key).map(|material| material.info)
}

/// What is stored in `dir` right now, without generating anything (so the GUI
/// can show the fingerprint while the server is stopped).
pub fn stored_info(dir: &Path) -> Option<TlsInfo> {
    let meta: Meta = serde_json::from_slice(&std::fs::read(dir.join(META_FILE)).ok()?).ok()?;
    let cert = dir.join(CERT_FILE);
    let der = CertificateDer::pem_file_iter(&cert).ok()?.next()?.ok()?;
    Some(TlsInfo {
        fingerprint_sha256: fingerprint_sha256(&der),
        source: CertSource::SelfSigned,
        cert_path: cert,
        names: meta.names,
        not_after: Some(meta.not_after),
    })
}

/// A rustls acceptor for the material (HTTP/1.1 only: WebSockets are not
/// upgraded over HTTP/2, and the listener page needs nothing from it).
pub fn acceptor(material: &TlsMaterial) -> Result<TlsAcceptor, TlsError> {
    let provider = Arc::new(rustls::crypto::ring::default_provider());
    let mut config = rustls::ServerConfig::builder_with_provider(provider)
        .with_safe_default_protocol_versions()
        .map_err(|e| TlsError::Setup(e.to_string()))?
        .with_no_client_auth()
        .with_single_cert(material.certs.clone(), material.key.clone_key())
        .map_err(|e| TlsError::KeyMismatch(e.to_string()))?;
    config.alpn_protocols = vec![b"http/1.1".to_vec()];
    Ok(TlsAcceptor::from(Arc::new(config)))
}

// ---------------------------------------------------------------------------
// What the running server uses (for the GUI)
// ---------------------------------------------------------------------------

static ACTIVE: Mutex<Option<TlsInfo>> = Mutex::new(None);

/// The certificate the running HTTPS server uses, `None` while it serves HTTP
/// or is stopped. Cheap; safe to call every frame.
pub fn active_info() -> Option<TlsInfo> {
    ACTIVE.lock().ok().and_then(|g| g.clone())
}

/// Record (or, with `None`, forget) the certificate in use.
pub fn set_active_info(info: Option<TlsInfo>) {
    if let Ok(mut guard) = ACTIVE.lock() {
        *guard = info;
    }
}

/// Everything a start needs: certificate, acceptor, log line, active info.
///
/// Blocking but short (a few small files, and a key generation the first
/// time), so it can run on the server thread.
pub fn prepare(settings: &TlsSettings) -> Result<TlsAcceptor, TlsError> {
    let material = load_or_create(settings, &SanSet::detect())?;
    let acceptor = acceptor(&material)?;
    let info = material.info;
    info!(
        "HTTPS enabled ({}): certificate {} SHA-256 {}",
        match info.source {
            CertSource::Custom => "your certificate",
            CertSource::SelfSigned => "self-signed",
        },
        info.cert_path.display(),
        info.fingerprint_sha256
    );
    if info.source == CertSource::SelfSigned {
        info!("Browsers will warn about a self-signed certificate: compare this fingerprint with the one the warning shows, then continue");
    }
    set_active_info(Some(info));
    Ok(acceptor)
}

