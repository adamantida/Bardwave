/// The names and addresses a generated certificate should be valid for.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct SanSet {
    /// DNS names (`localhost`, the host name, `<host>.local`).
    pub dns: Vec<String>,
    /// IP addresses (loopback and the current LAN addresses).
    pub ips: Vec<IpAddr>,
}

impl SanSet {
    /// `localhost`, `127.0.0.1`, `::1`, the host name and the LAN addresses of
    /// this machine right now.
    pub fn detect() -> Self {
        let mut set = Self::default();
        set.add_dns("localhost");
        if let Some(host) = host_name() {
            set.add_dns(&host);
            if !host.contains('.') {
                set.add_dns(&format!("{host}.local"));
            }
        }
        set.add_ip(IpAddr::V4(std::net::Ipv4Addr::LOCALHOST));
        set.add_ip(IpAddr::V6(std::net::Ipv6Addr::LOCALHOST));
        for ip in crate::network::local_ip::candidates() {
            set.add_ip(ip);
        }
        set
    }

    /// Add a DNS name when it is a plain host name a certificate can carry.
    pub fn add_dns(&mut self, name: &str) {
        let name = name.trim().trim_end_matches('.').to_ascii_lowercase();
        let valid = !name.is_empty()
            && name.len() <= 253
            && name
                .bytes()
                .all(|b| b.is_ascii_alphanumeric() || b == b'-' || b == b'.')
            && !name.starts_with('-')
            && !name.starts_with('.')
            && !name.contains("..");
        if valid && !self.dns.contains(&name) {
            self.dns.push(name);
        }
    }

    /// Add an address once.
    pub fn add_ip(&mut self, ip: IpAddr) {
        if !self.ips.contains(&ip) {
            self.ips.push(ip);
        }
    }

    /// Every entry as text (DNS names first).
    pub fn names(&self) -> Vec<String> {
        self.dns
            .iter()
            .cloned()
            .chain(self.ips.iter().map(|ip| ip.to_string()))
            .collect()
    }

    /// The addresses another machine could use to reach this one.
    fn external_ips(&self) -> impl Iterator<Item = &IpAddr> {
        self.ips.iter().filter(|ip| !ip.is_loopback())
    }
}

/// The machine's host name, when it can be determined.
pub fn host_name() -> Option<String> {
    #[cfg(unix)]
    {
        let mut buf = [0u8; 256];
        // SAFETY: the buffer is valid for `buf.len()` bytes and gethostname
        // writes at most that many (NUL-terminated unless truncated).
        let rc = unsafe { libc::gethostname(buf.as_mut_ptr().cast(), buf.len() - 1) };
        if rc != 0 {
            return None;
        }
        let end = buf.iter().position(|&b| b == 0).unwrap_or(buf.len());
        let name = String::from_utf8_lossy(&buf[..end]).trim().to_string();
        (!name.is_empty()).then_some(name)
    }
    #[cfg(not(unix))]
    {
        // UNVERIFIED on Windows: COMPUTERNAME is set for every session.
        std::env::var("COMPUTERNAME")
            .ok()
            .map(|n| n.trim().to_string())
            .filter(|n| !n.is_empty())
    }
}

