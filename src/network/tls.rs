/// Subdirectory of the data directory that holds the generated certificate.
pub const TLS_DIR: &str = "tls";
/// Generated certificate (PEM).
pub const CERT_FILE: &str = "cert.pem";
/// Generated private key (PEM, mode 0600 on Unix).
pub const KEY_FILE: &str = "key.pem";
/// Names and validity of the generated certificate.
pub const META_FILE: &str = "meta.json";

/// A generated certificate is valid this long. Apple platforms reject longer
/// validity for certificates that are not issued by a public CA.
const VALIDITY_DAYS: i64 = 397;
/// Replace a generated certificate when less than this is left.
pub const RENEW_BEFORE_DAYS: i64 = 30;
/// How long a client may take to finish the TLS handshake.
const HANDSHAKE_TIMEOUT: Duration = Duration::from_secs(10);
/// How long a client may take to send the request head.
const HEADER_TIMEOUT: Duration = Duration::from_secs(15);

/// What the application needs to know to serve HTTPS.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct TlsSettings {
    /// `server.tls`
    pub enabled: bool,
    /// `server.tls_cert`
    pub cert: Option<PathBuf>,
    /// `server.tls_key`
    pub key: Option<PathBuf>,
    /// Where a generated certificate lives. `None` is `<data dir>/tls`.
    pub dir: Option<PathBuf>,
}

impl TlsSettings {
    /// Read the `[server]` section. Empty path strings count as unset.
    pub fn from_config(server: &crate::config::ServerConfig) -> Self {
        let path = |p: &Option<String>| {
            p.as_deref()
                .map(str::trim)
                .filter(|p| !p.is_empty())
                .map(PathBuf::from)
        };
        Self {
            enabled: server.tls,
            cert: path(&server.tls_cert),
            key: path(&server.tls_key),
            dir: None,
        }
    }

    /// The directory a generated certificate is kept in.
    pub fn cert_dir(&self) -> PathBuf {
        self.dir
            .clone()
            .unwrap_or_else(|| crate::paths::data_dir().join(TLS_DIR))
    }

    /// Whether the operator supplied their own certificate.
    pub fn uses_custom_certificate(&self) -> bool {
        self.cert.is_some() || self.key.is_some()
    }
}

/// Where the certificate in use came from.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum CertSource {
    /// `server.tls_cert` / `server.tls_key`
    Custom,
    /// Generated by Bardwave, kept in the data directory.
    SelfSigned,
}

/// Public facts about the certificate in use, for the log and the GUI.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct TlsInfo {
    /// SHA-256 of the leaf certificate, upper-case hex with `:` separators.
    pub fingerprint_sha256: String,
    /// Own certificate or generated one.
    pub source: CertSource,
    /// The certificate file.
    pub cert_path: PathBuf,
    /// Names the generated certificate covers (empty for a custom one).
    pub names: Vec<String>,
    /// Unix time the certificate expires (generated ones only).
    pub not_after: Option<i64>,
}

/// A certificate chain and its key, ready to serve.
pub struct TlsMaterial {
    certs: Vec<CertificateDer<'static>>,
    key: PrivateKeyDer<'static>,
    /// What is shown to the operator.
    pub info: TlsInfo,
}

/// Why HTTPS could not be set up. The messages are shown to the operator.
#[derive(Debug, thiserror::Error)]
pub enum TlsError {
    #[error("cannot read the TLS certificate {path}: {reason}")]
    CertRead { path: PathBuf, reason: String },
    #[error("cannot read the TLS private key {path}: {reason}")]
    KeyRead { path: PathBuf, reason: String },
    #[error("{0} contains no certificate (expected a PEM file with BEGIN CERTIFICATE)")]
    NoCertificate(PathBuf),
    #[error("tls_cert and tls_key must be set together (or both removed to use a self-signed certificate)")]
    HalfConfigured,
    #[error("the TLS key does not belong to the certificate: {0}")]
    KeyMismatch(String),
    #[error("cannot create the self-signed certificate: {0}")]
    Generate(String),
    #[error("cannot store the self-signed certificate in {path}: {reason}")]
    Store { path: PathBuf, reason: String },
    #[error("TLS setup failed: {0}")]
    Setup(String),
}

