//! Optional HTTPS for remote access (`server.tls`).
//!
//! The game-master token and the listener key travel in the URL and in the
//! `/ws/control` handshake, so over the internet they must not cross the wire
//! in clear text. With `server.tls = true` the very same port speaks HTTPS and
//! `wss://` (no redirect is needed: there is only one port); with the default
//! `false` nothing here runs and the LAN keeps using plain HTTP.
//!
//! Certificates:
//!
//! * `server.tls_cert` / `server.tls_key` -- the operator's own PEM files (for
//!   example from Let's Encrypt or Caddy) are used as they are;
//! * otherwise a self-signed certificate is generated once with rcgen and kept
//!   in `<data dir>/tls/` (`cert.pem`, `key.pem` -- mode 0600 on Unix -- and
//!   a small `meta.json`). It is reused on the next start and replaced when it
//!   is about to expire or when none of this machine's current LAN addresses
//!   is covered any more (the laptop moved to another network), or on demand
//!   ([`regenerate_self_signed`]).
//!
//! The SHA-256 fingerprint of the certificate in use is logged and available
//! through [`active_info`] / [`stored_info`], so the game master can compare it
//! with the one a phone shows next to the self-signed certificate warning.
//!
//! The TLS layer is rustls with the `ring` provider (already in the tree via
//! ureq) over the listener the server already has: [`serve`] is the accept
//! loop that replaces `axum::serve` in this mode.

